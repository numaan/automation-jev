import { chromium, type Locator, type Page } from "playwright";
import { extractCandidates, locatorSource, describe } from "./extract.js";
import { decideNextAction, chooseValueFor, DONE, GIVE_UP } from "./jev.js";
import type { Candidate, Step, Task } from "./types.js";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";

/** Resolve a candidate to a live Playwright Locator, preferring semantic locators. */
function resolveLocator(page: Page, c: Candidate): Locator {
  if (c.kind === "fill") {
    if (c.ariaLabel) return page.getByLabel(c.ariaLabel).first();
    if (c.name && c.name !== c.placeholder) return page.getByLabel(c.name).first();
    if (c.placeholder) return page.getByPlaceholder(c.placeholder).first();
    return page.locator(c.css).first();
  }
  if ((c.role === "button" || c.role === "link") && c.name) {
    return page.getByRole(c.role as "button" | "link", { name: c.name }).first();
  }
  return page.locator(c.css).first();
}

export async function record(task: Task): Promise<Step[]> {
  const {
    goal,
    startUrl,
    data = {},
    maxSteps = 20,
    minConfidence = 0.4,
    doneThreshold = 0.8,
    headless = false,
    out = "generated/recorded.spec.ts",
  } = task;

  const browser = await chromium.launch({ headless });
  const page = await browser.newPage();
  const steps: Step[] = [];
  const history: string[] = [];

  await page.goto(startUrl, { waitUntil: "domcontentloaded" });
  steps.push({ action: "goto", locator: "", url: startUrl, note: `open ${startUrl}` });

  try {
    for (let i = 0; i < maxSteps; i++) {
      await page.waitForLoadState("domcontentloaded").catch(() => {});
      const candidates = await extractCandidates(page);
      const currentUrl = page.url();
      const pageTitle = await page.title();

      console.log(`\n── step ${i + 1} · ${currentUrl}`);
      console.log(`   ${candidates.length} candidate elements`);

      if (candidates.length === 0) {
        console.log("   no interactive elements found; stopping.");
        break;
      }

      const decision = await decideNextAction({
        goal,
        currentUrl,
        pageTitle,
        history,
        candidates,
        data,
      });

      console.log(
        `   Jev → ${decision.pick} (conf ${decision.confidence.toFixed(2)}, ` +
          `goalComplete ${decision.goalComplete.toFixed(2)})`
      );

      if (decision.goalComplete >= doneThreshold || decision.pick === DONE) {
        console.log("   goal judged complete. done.");
        break;
      }
      if (decision.pick === GIVE_UP) {
        console.log("   Jev sees no useful action here. stopping.");
        break;
      }
      if (decision.confidence < minConfidence) {
        console.log(
          `   confidence ${decision.confidence.toFixed(2)} below ${minConfidence}; stopping to avoid a blind click.`
        );
        break;
      }

      const chosen = candidates.find((c) => c.id === decision.pick);
      if (!chosen) {
        console.log("   picked id not found; stopping.");
        break;
      }

      const loc = resolveLocator(page, chosen);
      const src = locatorSource(chosen);

      if (chosen.kind === "fill") {
        const { key, confidence } = await chooseValueFor({ goal, field: chosen, data });
        if (!key) {
          console.log("   no data value fits this field; stopping.");
          break;
        }
        const value = data[key];
        console.log(`   fill "${chosen.name}" ← data.${key} (conf ${confidence.toFixed(2)})`);
        await loc.fill(value);
        steps.push({
          action: "fill",
          locator: src,
          value,
          note: `fill ${describe(chosen)} with data.${key}`,
        });
        history.push(`Filled "${chosen.name}" with the ${key} value.`);
      } else {
        console.log(`   click ${describe(chosen)}`);
        await Promise.all([
          loc.click(),
          page.waitForLoadState("domcontentloaded").catch(() => {}),
        ]);
        steps.push({ action: "click", locator: src, note: `click ${describe(chosen)}` });
        history.push(`Clicked "${chosen.name || chosen.role}".`);
      }

      await page.waitForTimeout(400); // let SPA transitions settle
    }
  } finally {
    await browser.close();
  }

  const script = emitScript(task, steps);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, script, "utf8");
  console.log(`\n✔ ${steps.length} steps recorded → ${out}`);
  return steps;
}

/** Turn the recorded steps into a standalone @playwright/test spec. */
function emitScript(task: Task, steps: Step[]): string {
  const q = (s: string) => JSON.stringify(s);
  const lines: string[] = [];
  lines.push(`import { test, expect } from "@playwright/test";`);
  lines.push("");
  lines.push(`// Generated by the Jev Playwright recorder.`);
  lines.push(`// Goal: ${task.goal}`);
  lines.push("");
  lines.push(`test(${q(task.goal.slice(0, 80))}, async ({ page }) => {`);
  for (const s of steps) {
    lines.push(`  // ${s.note}`);
    if (s.action === "goto") {
      lines.push(`  await page.goto(${q(s.url!)});`);
    } else if (s.action === "click") {
      lines.push(`  await ${s.locator}.click();`);
    } else if (s.action === "fill") {
      lines.push(`  await ${s.locator}.fill(${q(s.value ?? "")});`);
    }
  }
  lines.push("");
  lines.push(`  // TODO: add an assertion that proves the goal was reached, e.g.`);
  lines.push(`  // await expect(page.getByText("Success")).toBeVisible();`);
  lines.push(`});`);
  lines.push("");
  return lines.join("\n");
}
